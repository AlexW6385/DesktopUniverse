"""
Export the built-in presets and the panel schema for the web version.

    python web/export.py

writes web/data.js (presets in order, hotkey slots, schema, defaults) and, if Pillow is
installed, web/thumbs/<key>.jpg from the screenshots in docs/. Needs nothing else:
config.py and presets.py are plain Python.
"""

import json
import sys
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import config  # noqa: E402
import presets  # noqa: E402


def main():
    data = {
        "order": presets.BUILTIN_KEYS,
        "slots": presets.SLOTS,
        "presets": {key: config.to_dict(make()) for key, make in presets.BUILTIN},
        "schema": config.SCHEMA,
        "laws": config.LAW_HINTS,
        "defaults": {
            "preset": config.to_dict(config.Preset()),
            "layer": config.layer_template(),
            "field": config._clean(asdict(config.Field())),
        },
        "max_pairs": config.MAX_PAIRS,
    }
    text = "// generated by web/export.py from presets.py and config.py; do not edit\n" \
           "window.DU_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
    out = ROOT / "web" / "data.js"
    out.write_text(text, encoding="utf-8")
    print(f"{out.relative_to(ROOT)}: {len(data['presets'])} presets, {len(text) // 1024} KB")

    try:
        from PIL import Image
    except ImportError:
        print("Pillow not installed: thumbnails left as they are")
        return
    thumbs = ROOT / "web" / "thumbs"
    thumbs.mkdir(exist_ok=True)
    for old in thumbs.glob("*.jpg"):                       # presets that are gone
        if old.stem not in presets.BUILTIN_KEYS:
            old.unlink()
    for key in data["presets"]:
        src = ROOT / "docs" / f"{key}.jpg"
        if src.exists():
            Image.open(src).resize((384, 240), Image.LANCZOS).save(thumbs / f"{key}.jpg", quality=82)
    print(f"web/thumbs: {len(list(thumbs.glob('*.jpg')))} thumbnails")


if __name__ == "__main__":
    main()
